-- ChatZynk Supabase setup
-- Run the whole script in Supabase Dashboard → SQL Editor → New query.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  gender text not null,
  age int not null check (age between 13 and 120),
  country text not null,
  online boolean not null default false,
  last_seen timestamptz not null default now(),
  message_privacy text not null default 'everyone' check (message_privacy in ('everyone','friends')),
  notifications boolean not null default true,
  theme text not null default 'dark' check (theme in ('dark','light')),
  created_at timestamptz not null default now()
);

create table if not exists public.friendships (
  user_id uuid not null references public.profiles(id) on delete cascade,
  friend_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, friend_id),
  check (user_id <> friend_id)
);

create table if not exists public.blocks (
  user_id uuid not null references public.profiles(id) on delete cascade,
  blocked_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, blocked_id),
  check (user_id <> blocked_id)
);

create table if not exists public.groups (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  icon text not null default '👥',
  admin_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.group_members (
  group_id uuid not null references public.groups(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null default 'member' check (role in ('admin','member')),
  joined_at timestamptz not null default now(),
  primary key (group_id,user_id)
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  group_id uuid references public.groups(id) on delete cascade,
  conversation_id text,
  body text not null default '',
  media_type text check (media_type in ('image','audio') or media_type is null),
  media_url text,
  created_at timestamptz not null default now(),
  check ((group_id is not null and conversation_id is null) or (group_id is null and conversation_id is not null))
);
create index if not exists messages_group_created_idx on public.messages(group_id,created_at);
create index if not exists messages_conversation_created_idx on public.messages(conversation_id,created_at);

alter table public.profiles enable row level security;
alter table public.friendships enable row level security;
alter table public.blocks enable row level security;
alter table public.groups enable row level security;
alter table public.group_members enable row level security;
alter table public.messages enable row level security;

drop policy if exists "profiles visible to signed in users" on public.profiles;
create policy "profiles visible to signed in users" on public.profiles for select to authenticated using (true);
drop policy if exists "users create own profile" on public.profiles;
create policy "users create own profile" on public.profiles for insert to authenticated with check (id = auth.uid());
drop policy if exists "users update own profile" on public.profiles;
create policy "users update own profile" on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());

drop policy if exists "friendships readable by owner" on public.friendships;
create policy "friendships readable by owner" on public.friendships for select to authenticated using (user_id = auth.uid());
drop policy if exists "users add own friendships" on public.friendships;
create policy "users add own friendships" on public.friendships for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "users remove own friendships" on public.friendships;
create policy "users remove own friendships" on public.friendships for delete to authenticated using (user_id = auth.uid());

drop policy if exists "blocks readable by owner" on public.blocks;
create policy "blocks readable by owner" on public.blocks for select to authenticated using (user_id = auth.uid());
drop policy if exists "users create own blocks" on public.blocks;
create policy "users create own blocks" on public.blocks for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "users remove own blocks" on public.blocks;
create policy "users remove own blocks" on public.blocks for delete to authenticated using (user_id = auth.uid());

drop policy if exists "members can view groups" on public.groups;
create policy "members can view groups" on public.groups for select to authenticated using (exists(select 1 from public.group_members gm where gm.group_id=id and gm.user_id=auth.uid()));
drop policy if exists "users create groups" on public.groups;
create policy "users create groups" on public.groups for insert to authenticated with check (admin_id=auth.uid());
drop policy if exists "admins update groups" on public.groups;
create policy "admins update groups" on public.groups for update to authenticated using (admin_id=auth.uid()) with check (admin_id=auth.uid());
drop policy if exists "admins delete groups" on public.groups;
create policy "admins delete groups" on public.groups for delete to authenticated using (admin_id=auth.uid());

drop policy if exists "group members view membership" on public.group_members;
create policy "group members view membership" on public.group_members for select to authenticated using (
 user_id=auth.uid() or exists(select 1 from public.group_members mine where mine.group_id=group_members.group_id and mine.user_id=auth.uid())
);
drop policy if exists "members can join themselves or admins add" on public.group_members;
create policy "group admins add members" on public.group_members for insert to authenticated with check (
 exists(select 1 from public.groups g where g.id=group_members.group_id and g.admin_id=auth.uid())
);
drop policy if exists "members leave or admins remove" on public.group_members;
create policy "members leave or admins remove" on public.group_members for delete to authenticated using (
 user_id=auth.uid() or exists(select 1 from public.groups g where g.id=group_id and g.admin_id=auth.uid())
);

drop policy if exists "participants read messages" on public.messages;
create policy "participants read messages" on public.messages for select to authenticated using (
 sender_id=auth.uid()
 or (group_id is not null and exists(select 1 from public.group_members gm where gm.group_id=messages.group_id and gm.user_id=auth.uid()))
 or (conversation_id is not null and position(auth.uid()::text in conversation_id)>0)
);
drop policy if exists "participants send messages" on public.messages;
create policy "participants send messages" on public.messages for insert to authenticated with check (
 sender_id=auth.uid()
 and ((group_id is not null and exists(select 1 from public.group_members gm where gm.group_id=messages.group_id and gm.user_id=auth.uid()))
   or (conversation_id is not null and position(auth.uid()::text in conversation_id)>0))
);

-- Public media URLs are used by the app. Uploads are restricted to the user's own folder.
insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types)
values ('chat-media','chat-media',true,15728640,array['image/*','audio/*'])
on conflict (id) do update set public=true,file_size_limit=15728640,allowed_mime_types=array['image/*','audio/*'];

drop policy if exists "chat media public read" on storage.objects;
create policy "chat media public read" on storage.objects for select using (bucket_id='chat-media');
drop policy if exists "users upload own chat media" on storage.objects;
create policy "users upload own chat media" on storage.objects for insert to authenticated with check (
 bucket_id='chat-media' and (storage.foldername(name))[1]=auth.uid()::text
);
drop policy if exists "users delete own chat media" on storage.objects;
create policy "users delete own chat media" on storage.objects for delete to authenticated using (
 bucket_id='chat-media' and (storage.foldername(name))[1]=auth.uid()::text
);

